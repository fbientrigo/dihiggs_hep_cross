#!/usr/bin/env python3
"""Python-3-safe standalone UFO external-parameter card writer.

This replaces the historical generated writer in the runtime copy only. It does
not alter particles, vertices, couplings, masses, or widths.
"""
from __future__ import annotations

import argparse
import importlib
import sys
from collections import defaultdict
from pathlib import Path


def _load_parameters():
    model_dir = Path(__file__).resolve().parent
    sys.path.insert(0, str(model_dir))
    try:
        obj = importlib.import_module('object_library')
        importlib.import_module('function_library')
        importlib.import_module('parameters')
        return list(obj.all_parameters)
    finally:
        if sys.path and sys.path[0] == str(model_dir):
            sys.path.pop(0)


def _parse_overrides(items):
    result = {}
    for item in items:
        if '=' not in item:
            raise ValueError(f'Override must be NAME=VALUE: {item}')
        name, value = item.split('=', 1)
        result[name.strip()] = float(value)
    return result


def write_param_card(output: Path, overrides: dict[str, float] | None = None) -> None:
    overrides = overrides or {}
    parameters = [p for p in _load_parameters() if getattr(p, 'nature', None) == 'external']
    names = {p.name for p in parameters}
    unknown = sorted(set(overrides) - names)
    if unknown:
        raise ValueError(f'Unknown external parameter override(s): {unknown}')

    blocks = defaultdict(list)
    decays = []
    for p in parameters:
        value = overrides.get(p.name, p.value)
        value = complex(value).real
        block = str(p.lhablock).upper()
        if block == 'DECAY':
            decays.append((tuple(p.lhacode), value, p.name))
        else:
            blocks[block].append((tuple(p.lhacode), value, p.name))

    lines = [
        '# Deterministic param_card.dat generated by the 2Higgs UFO pack',
        '# Project lifetime input is mm; FRBLOCK 2 (ctauh2) is metres.',
        '# h2 width is internal in the production UFO and must not be set to Auto.',
        '',
    ]
    for block in sorted(blocks):
        lines.append(f'BLOCK {block}')
        for code, value, name in sorted(blocks[block]):
            index = ' '.join(str(x) for x in code)
            lines.append(f'  {index:<12} {value:.16e} # {name}')
        lines.append('')
    for code, value, name in sorted(decays):
        if len(code) != 1:
            raise ValueError(f'Unexpected DECAY code for {name}: {code}')
        lines.append(f'DECAY {code[0]:>9d} {value:.16e} # {name}')
    lines.append('')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', default='param_card.dat')
    parser.add_argument('--set', action='append', default=[], metavar='NAME=VALUE')
    args = parser.parse_args()
    try:
        write_param_card(Path(args.output), _parse_overrides(args.set))
    except Exception as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 2
    print(Path(args.output).resolve())
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
